import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assets = resolve(root, "assets", "holo");
const output = resolve(root, "src", "generated", "holo-assets.ts");
const fixtureOutput = resolve(root, "src", "generated", "holo-fixtures.ts");
const capsuleAssets = resolve(root, "assets", "capsules");
const capsuleOutput = resolve(root, "src", "generated", "capsule-fixtures.ts");
const files = {
  viewerHtml: "viewer.html",
  hologramCss: "hologram.css",
  threeR128: "three-r128.min.js",
  holoProtocol: "holo-protocol.js",
  hologramRuntime: "hologram-runtime.js",
};
const fixtures = {
  demoHoloRaw: "demo-holo.json",
  demoSourceRaw: "demo-source.json",
};
const entries = await Promise.all(
  Object.entries(files).map(async ([name, file]) => [
    name,
    await readFile(resolve(assets, file), "utf8"),
  ]),
);
const body = [
  "/* Generated by scripts/sync-holo-assets.mjs. Do not edit directly. */",
  ...entries.map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`),
  "",
].join("\n");
await writeFile(output, body);
const fixtureEntries = await Promise.all(
  Object.entries(fixtures).map(async ([name, file]) => [
    name,
    await readFile(resolve(assets, file), "utf8"),
  ]),
);
await writeFile(
  fixtureOutput,
  [
    "/* Generated by scripts/sync-holo-assets.mjs. Do not edit directly. */",
    ...fixtureEntries.map(
      ([name, value]) => `export const ${name} = ${JSON.stringify(value)};`,
    ),
    "",
  ].join("\n"),
);
const capsuleFiles = {
  capsuleGalleryRaw: "gallery.json",
  lumenDriftCapsuleRaw: "lumen-drift.rollingcore.json",
  meshBloomCapsuleRaw: "mesh-bloom.rollingcore.json",
  meshBloomRegistryRaw: "mesh-bloom.registry.json",
  orbitalGardenCapsuleRaw: "orbital-garden.rollingcore.json",
  orbitalGardenRegistryRaw: "orbital-garden.registry.json",
  lifecycleFixturesRaw: "lifecycle-fixtures.json",
};
const capsuleEntries = await Promise.all(
  Object.entries(capsuleFiles).map(async ([name, file]) => [
    name,
    await readFile(resolve(capsuleAssets, file), "utf8"),
  ]),
);
await writeFile(
  capsuleOutput,
  [
    "/* Generated by scripts/sync-holo-assets.mjs. Do not edit directly. */",
    ...capsuleEntries.map(
      ([name, value]) => `export const ${name} = ${JSON.stringify(value)};`,
    ),
    "",
  ].join("\n"),
);
console.log(`Wrote ${output}`);
console.log(`Wrote ${fixtureOutput}`);
console.log(`Wrote ${capsuleOutput}`);
